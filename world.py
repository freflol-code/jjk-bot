def get_world_map_text(current_x: int) -> str:
    """Текстовая полоска карты с указанием текущей позиции игрока.
    Стрелка — юникод (←), а не '<', чтобы не ломать HTML-парсер Telegram."""
    clamped_x = clamp_x(current_x)
    lines = []
    for district in DISTRICTS:
        marker = " 👤 ← ТЫ ЗДЕСЬ" if district["x_min"] <= clamped_x <= district["x_max"] else ""
        lines.append(f"{district['emoji']} {district['name']} (X: {district['x_min']}..{district['x_max']}){marker}")
    return "\n".join(lines)
