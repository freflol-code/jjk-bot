def clamp_x(x: int) -> int:
    """Ограничивает координату крайними точками карты."""
    return max(MIN_X, min(MAX_X, x))


def is_valid_x(x: int) -> bool:
    """Проверяет, находится ли координата в пределах доступного мира."""
    return MIN_X <= x <= MAX_X


def get_district_by_x(x: int) -> dict:
    """Возвращает район, в котором находится координата x."""
    clamped_x = clamp_x(x)
    for district in DISTRICTS:
        if district["x_min"] <= clamped_x <= district["x_max"]:
            return district
    return DISTRICTS[0] if clamped_x < 0 else DISTRICTS[-1]


def get_district_by_id(district_id: str) -> dict | None:
    """Возвращает район по его id или None, если такого нет."""
    for district in DISTRICTS:
        if district["id"] == district_id:
            return district
    return None


def is_safe_district(district: dict) -> bool:
    """True, если в районе запрещён спавн проклятий (безопасная зона)."""
    return bool(district.get("safe"))


def get_neighbor_district(current_x: int, direction: str) -> dict | None:
    """Возвращает район, следующий за текущим в указанном направлении.

    direction: 'left' или 'right'.
    None, если текущий район граничит с краем мира.
    """
    current = get_district_by_x(current_x)
    if direction == "left":
        candidates = [d for d in DISTRICTS if d["x_max"] < current["x_min"]]
        if not candidates:
            return None
        return max(candidates, key=lambda d: d["x_max"])
    if direction == "right":
        candidates = [d for d in DISTRICTS if d["x_min"] > current["x_max"]]
        if not candidates:
            return None
        return min(candidates, key=lambda d: d["x_min"])
    return None


